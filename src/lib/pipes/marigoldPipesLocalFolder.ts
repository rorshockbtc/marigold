import { MerkleDagManifest } from '../crypto/merkleDagAndOtsBridge';

export interface MarigoldHarnessBlueprint {
  $schema: 'https://pipes.pink/schemas/v1/harness.json';
  namespace: 'marigold-duckdb';
  name: string;
  version: string;
  firstParty: true;
  provisionCostCredits: 10;
  engine: string;
  merkleTree: string;
  privacyGuarantee: string;
  datasetSummary: {
    datasetName: string;
    totalRows: number;
    merkleRoot: string;
    dagNodeCount: number;
    generatedAt: string;
  };
  mcpConfig: {
    mcpServers: {
      'pipes-marigold': {
        command: string;
        args: string[];
      };
    };
  };
}

export interface LocalFolderProvisionResult {
  success: boolean;
  mode: 'fs-access' | 'download';
  folderName: string;
  filesWritten: string[];
  message: string;
}

