/**
 * 1-Click Provisioner using the browser's native File System Access API (`showDirectoryPicker`)
 * with automatic download fallback for browsers without directory picker support.
 */
export async function provisionMarigoldAndPipesLocalFolder(params: {
  datasetName: string;
  totalRows: number;
  dossierTitle: string;
  narrativePlain: string;
  dagManifest: MerkleDagManifest;
  relatedPipes: string[];
  bridgedConcepts: string[];
}): Promise<LocalFolderProvisionResult> {
  const harness = generateMarigoldHarnessBlueprint({
    datasetName: params.datasetName,
    totalRows: params.totalRows,
    dagManifest: params.dagManifest,
  });
  const skillMd = buildMarigoldSkillMarkdown(params);
  const guideMd = buildAgentOperatingGuide({
    datasetName: params.datasetName,
    merkleRoot: params.dagManifest.merkleRoot,
  });

  const win = typeof window !== 'undefined' ? (window as any) : null;
  if (win && typeof win.showDirectoryPicker === 'function') {
    try {
      const parentHandle = await win.showDirectoryPicker({
        id: 'marigold-pipes-local',
        mode: 'readwrite',
        startIn: 'documents',
      });

      const rootHandle =
        parentHandle.name === 'Marigold_Local' || parentHandle.name === 'Pipes_Local'
          ? parentHandle
          : await parentHandle.getDirectoryHandle('Marigold_Local', { create: true });

      const pipesDir = await rootHandle.getDirectoryHandle('pipes', { create: true });
      const memoryDir = await rootHandle.getDirectoryHandle('memory', { create: true });
      const dossiersDir = await rootHandle.getDirectoryHandle('dossiers', { create: true });
      const proofsDir = await rootHandle.getDirectoryHandle('proofs', { create: true });

      await writeFileToDir(rootHandle, 'README_START_HERE.md', guideMd);
      await writeFileToDir(memoryDir, 'AGENT_OPERATING_GUIDE.md', guideMd);
      await writeFileToDir(pipesDir, 'marigoldinsights-skill.md', skillMd);
      await writeFileToDir(dossiersDir, 'marigold.json', JSON.stringify(harness, null, 2));
      await writeFileToDir(
        proofsDir,
        'merkle_dag.json',
        JSON.stringify(params.dagManifest, null, 2)
      );

      return {
        success: true,
        mode: 'fs-access',
        folderName: rootHandle.name,
        filesWritten: [
          `${rootHandle.name}/README_START_HERE.md`,
          `${rootHandle.name}/memory/AGENT_OPERATING_GUIDE.md`,
          `${rootHandle.name}/pipes/marigoldinsights-skill.md`,
          `${rootHandle.name}/dossiers/marigold.json`,
          `${rootHandle.name}/proofs/merkle_dag.json`,
        ],
        message: `Provisioned ${rootHandle.name} on your computer with marigoldinsights-skill.md, AGENT_OPERATING_GUIDE.md, marigold.json, and merkle_dag.json!`,
      };
    } catch (err: any) {
      if (err && err.name === 'AbortError') {
        return {
          success: false,
          mode: 'fs-access',
          folderName: 'Marigold_Local',
          filesWritten: [],
          message: 'Folder selection was canceled.',
        };
      }
    }
  }

  // Fallback for Safari/Firefox: trigger clean downloads
  if (typeof document !== 'undefined') {
    downloadTextFile('marigoldinsights-skill.md', skillMd, 'text/markdown;charset=utf-8');
    setTimeout(() => {
      downloadTextFile(
        'marigold.json',
        JSON.stringify(harness, null, 2),
        'application/json;charset=utf-8'
      );
    }, 200);
  }

  return {
    success: true,
    mode: 'download',
    folderName: 'Marigold_Local',
    filesWritten: ['marigoldinsights-skill.md', 'marigold.json'],
    message:
      'Downloaded marigoldinsights-skill.md and marigold.json! Place them inside your ~/Documents/Marigold_Local or ~/Documents/Pipes_Local folder.',
  };
}

async function writeFileToDir(dirHandle: any, filename: string, content: string) {
  const fh = await dirHandle.getFileHandle(filename, { create: true });
  const writable = await fh.createWritable();
  await writable.write(content);
  await writable.close();
}

function downloadTextFile(filename: string, content: string, mime: string) {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}
